-- Warm-Flow 1.8.8 工作流引擎表结构（MySQL）
-- 说明：该脚本仅创建 flow_* 前缀的工作流表，不会触碰任何业务表；
--       应用启动时 WarmFlowSchemaInitializer 会自动执行本脚本（全部为 CREATE TABLE IF NOT EXISTS，可重复执行）。
--       也可手工导入：mysql -u root -p ssl_ca < db/warm-flow.sql

CREATE TABLE IF NOT EXISTS flow_definition (
    id              BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键id',
    create_time     DATETIME                      DEFAULT NULL COMMENT '创建时间',
    update_time     DATETIME                      DEFAULT NULL COMMENT '更新时间',
    create_by       VARCHAR(64)                   DEFAULT NULL COMMENT '创建者',
    update_by       VARCHAR(64)                   DEFAULT NULL COMMENT '更新者',
    tenant_id       VARCHAR(40)                   DEFAULT NULL COMMENT '租户id',
    del_flag        CHAR(1)                       DEFAULT '0' COMMENT '删除标志',
    flow_code       VARCHAR(40)  NOT NULL COMMENT '流程编码',
    flow_name       VARCHAR(100) NOT NULL COMMENT '流程名称',
    model_value     LONGTEXT COMMENT '流程模型（设计器快照）',
    category        VARCHAR(100)                  DEFAULT NULL COMMENT '流程分类',
    version         VARCHAR(20)  NOT NULL COMMENT '流程版本',
    is_publish      TINYINT      NOT NULL DEFAULT 0 COMMENT '是否发布 0未发布 1已发布 9失效',
    form_custom     CHAR(1)                       DEFAULT 'N' COMMENT '表单是否自定义 Y/N',
    form_path       VARCHAR(100)                  DEFAULT NULL COMMENT '表单路径',
    activity_status TINYINT      NOT NULL DEFAULT 1 COMMENT '激活状态 0挂起 1激活',
    listener_type   VARCHAR(100)                  DEFAULT NULL COMMENT '监听器类型',
    listener_path   VARCHAR(400)                  DEFAULT NULL COMMENT '监听器路径',
    ext             VARCHAR(500)                  DEFAULT NULL COMMENT '扩展字段',
    PRIMARY KEY (id),
    KEY idx_def_flow_code (flow_code),
    KEY idx_def_publish (is_publish)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '流程定义表';

CREATE TABLE IF NOT EXISTS flow_node (
    id              BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键id',
    create_time     DATETIME                      DEFAULT NULL COMMENT '创建时间',
    update_time     DATETIME                      DEFAULT NULL COMMENT '更新时间',
    create_by       VARCHAR(64)                   DEFAULT NULL COMMENT '创建者',
    update_by       VARCHAR(64)                   DEFAULT NULL COMMENT '更新者',
    tenant_id       VARCHAR(40)                   DEFAULT NULL COMMENT '租户id',
    del_flag        CHAR(1)                       DEFAULT '0' COMMENT '删除标志',
    node_type       TINYINT      NOT NULL DEFAULT 1 COMMENT '节点类型 0开始 1中间 2结束 3互斥网关 4并行网关',
    definition_id   BIGINT       NOT NULL COMMENT '流程定义id',
    node_code       VARCHAR(100) NOT NULL COMMENT '节点编码',
    node_name       VARCHAR(100)                  DEFAULT NULL COMMENT '节点名称',
    permission_flag VARCHAR(200)                  DEFAULT NULL COMMENT '权限标识，多个用@@分隔',
    node_ratio      VARCHAR(20)                   DEFAULT '0' COMMENT '签署比例值',
    coordinate      VARCHAR(100)                  DEFAULT NULL COMMENT '坐标',
    version         VARCHAR(20)  NOT NULL COMMENT '版本',
    any_node_skip   VARCHAR(100)                  DEFAULT NULL COMMENT '是否可退回任意节点 Y/N',
    listener_type   VARCHAR(100)                  DEFAULT NULL COMMENT '监听器类型',
    listener_path   VARCHAR(400)                  DEFAULT NULL COMMENT '监听器路径',
    form_custom     CHAR(1)                       DEFAULT 'N' COMMENT '表单是否自定义 Y/N',
    form_path       VARCHAR(100)                  DEFAULT NULL COMMENT '表单路径',
    ext             VARCHAR(500)                  DEFAULT NULL COMMENT '扩展字段',
    PRIMARY KEY (id),
    KEY idx_node_def (definition_id),
    KEY idx_node_code (node_code)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '流程节点表';

CREATE TABLE IF NOT EXISTS flow_skip (
    id              BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键id',
    create_time     DATETIME                      DEFAULT NULL COMMENT '创建时间',
    update_time     DATETIME                      DEFAULT NULL COMMENT '更新时间',
    create_by       VARCHAR(64)                   DEFAULT NULL COMMENT '创建者',
    update_by       VARCHAR(64)                   DEFAULT NULL COMMENT '更新者',
    tenant_id       VARCHAR(40)                   DEFAULT NULL COMMENT '租户id',
    del_flag        CHAR(1)                       DEFAULT '0' COMMENT '删除标志',
    definition_id   BIGINT       NOT NULL COMMENT '流程定义id',
    node_id         BIGINT                        DEFAULT NULL COMMENT '节点id',
    now_node_code   VARCHAR(100) NOT NULL COMMENT '当前节点编码',
    now_node_type   TINYINT                       DEFAULT NULL COMMENT '当前节点类型',
    next_node_code  VARCHAR(100) NOT NULL COMMENT '下一节点编码',
    next_node_type  TINYINT                       DEFAULT NULL COMMENT '下一节点类型',
    skip_name       VARCHAR(100)                  DEFAULT NULL COMMENT '跳转名称',
    skip_type       VARCHAR(10)                   DEFAULT NULL COMMENT '跳转类型 PASS/REJECT',
    skip_condition  VARCHAR(200)                  DEFAULT NULL COMMENT '跳转条件',
    coordinate      VARCHAR(100)                  DEFAULT NULL COMMENT '坐标',
    PRIMARY KEY (id),
    KEY idx_skip_def (definition_id),
    KEY idx_skip_now (now_node_code)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '节点跳转关联表';

CREATE TABLE IF NOT EXISTS flow_instance (
    id              BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键id',
    create_time     DATETIME                      DEFAULT NULL COMMENT '创建时间',
    update_time     DATETIME                      DEFAULT NULL COMMENT '更新时间',
    create_by       VARCHAR(64)                   DEFAULT NULL COMMENT '创建者',
    update_by       VARCHAR(64)                   DEFAULT NULL COMMENT '更新者',
    tenant_id       VARCHAR(40)                   DEFAULT NULL COMMENT '租户id',
    del_flag        CHAR(1)                       DEFAULT '0' COMMENT '删除标志',
    definition_id   BIGINT       NOT NULL COMMENT '流程定义id',
    flow_name       VARCHAR(100)                  DEFAULT NULL COMMENT '流程名称',
    business_id     VARCHAR(40)  NOT NULL COMMENT '业务id',
    started_by_user_id BIGINT    DEFAULT NULL COMMENT '发起人用户id',
    started_by_name VARCHAR(64)                   DEFAULT NULL COMMENT '发起人姓名快照',
    node_type       TINYINT      NOT NULL DEFAULT 0 COMMENT '当前节点类型',
    node_code       VARCHAR(40)  NOT NULL COMMENT '当前节点编码',
    node_name       VARCHAR(100)                  DEFAULT NULL COMMENT '当前节点名称',
    variable        TEXT COMMENT '任务变量',
    flow_status     VARCHAR(20)  NOT NULL COMMENT '流程状态',
    activity_status TINYINT      NOT NULL DEFAULT 1 COMMENT '激活状态 0挂起 1激活',
    form_custom     CHAR(1)                       DEFAULT 'N' COMMENT '表单是否自定义 Y/N',
    form_path       VARCHAR(100)                  DEFAULT NULL COMMENT '表单路径',
    def_json        LONGTEXT COMMENT '流程定义快照',
    ext             VARCHAR(500)                  DEFAULT NULL COMMENT '扩展字段',
    PRIMARY KEY (id),
    KEY idx_inst_def (definition_id),
    KEY idx_inst_business (business_id),
    KEY idx_inst_status (flow_status)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '流程实例表';

CREATE TABLE IF NOT EXISTS flow_task (
    id              BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键id',
    create_time     DATETIME                      DEFAULT NULL COMMENT '创建时间',
    update_time     DATETIME                      DEFAULT NULL COMMENT '更新时间',
    create_by       VARCHAR(64)                   DEFAULT NULL COMMENT '创建者',
    update_by       VARCHAR(64)                   DEFAULT NULL COMMENT '更新者',
    tenant_id       VARCHAR(40)                   DEFAULT NULL COMMENT '租户id',
    del_flag        CHAR(1)                       DEFAULT '0' COMMENT '删除标志',
    definition_id   BIGINT       NOT NULL COMMENT '流程定义id',
    instance_id     BIGINT       NOT NULL COMMENT '流程实例id',
    flow_name       VARCHAR(100)                  DEFAULT NULL COMMENT '流程名称',
    business_id     VARCHAR(40)                   DEFAULT NULL COMMENT '业务id',
    node_code       VARCHAR(100) NOT NULL COMMENT '节点编码',
    node_name       VARCHAR(100)                  DEFAULT NULL COMMENT '节点名称',
    node_type       TINYINT      NOT NULL DEFAULT 1 COMMENT '节点类型',
    flow_status     VARCHAR(20)                   DEFAULT NULL COMMENT '流程状态',
    form_custom     CHAR(1)                       DEFAULT 'N' COMMENT '表单是否自定义 Y/N',
    form_path       VARCHAR(100)                  DEFAULT NULL COMMENT '表单路径',
    PRIMARY KEY (id),
    KEY idx_task_inst (instance_id),
    KEY idx_task_def (definition_id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '待办任务表';

CREATE TABLE IF NOT EXISTS flow_his_task (
