CREATE TABLE IF NOT EXISTS flow_user (
    id           BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键id',
    create_time  DATETIME                      DEFAULT NULL COMMENT '创建时间',
    update_time  DATETIME                      DEFAULT NULL COMMENT '更新时间',
    create_by    VARCHAR(64)                   DEFAULT NULL COMMENT '创建人',
    update_by    VARCHAR(64)                   DEFAULT NULL COMMENT '更新人',
    tenant_id    VARCHAR(40)                   DEFAULT NULL COMMENT '租户id',
    del_flag     CHAR(1)                       DEFAULT '0' COMMENT '删除标志',
    type         CHAR(1)      NOT NULL COMMENT '人员类型 1审批人 2转办人 3委托人',
    processed_by VARCHAR(80)  NOT NULL COMMENT '权限人',
    associated   BIGINT       NOT NULL COMMENT '任务id',
    PRIMARY KEY (id),
    KEY idx_user_associated (associated),
    KEY idx_user_processed (processed_by)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '流程用户表';
