    del_flag         CHAR(1)                       DEFAULT '0' COMMENT '删除标志',
    definition_id    BIGINT                        DEFAULT NULL COMMENT '流程定义id',
    flow_name        VARCHAR(100)                  DEFAULT NULL COMMENT '流程名称',
    instance_id      BIGINT                        DEFAULT NULL COMMENT '流程实例id',
    task_id          BIGINT                        DEFAULT NULL COMMENT '任务id',
    cooperate_type   TINYINT                       DEFAULT 0 COMMENT '协作方式 1审批 2转办 3委派 4会签 5票签 6加签 7减签',
    business_id      VARCHAR(40)                   DEFAULT NULL COMMENT '业务id',
    node_code        VARCHAR(100)                  DEFAULT NULL COMMENT '节点编码',
    node_name        VARCHAR(100)                  DEFAULT NULL COMMENT '节点名称',
